/* Model: calc() turns an offer into figures. No DOM here. */

function irpfScale(base){
  let c=0, prev=0;
  for(const [cap,rate] of LAW.irpf.scale){ if(base<=prev) break; c+=(Math.min(base,cap)-prev)*rate; prev=cap }
  return c;
}
/** Earned-income reduction (LIRPF art. 20). */
function workReduction(rn){
  let red=0;
  const W=LAW.irpf.workReduction;
  if(rn<=W.fullTo) red=W.full;
  else if(rn<=W.midTo) red=W.full-W.midSlope*(rn-W.fullTo);
  else if(rn<=W.lowTo) red=W.lowFrom-W.lowSlope*(rn-W.midTo);
  return Math.max(0,red);
}
/** IRPF for the year on an annual gross (general scale, no children, with the deduction for wages near the minimum wage). */
function irpfTax(gross,ssPct,D){
  if(gross<=0) return 0;
  const rn=Math.max(0,gross-gross*ssPct/100-LAW.irpf.expenses);
  const base=Math.max(0,rn-workReduction(rn));
  const deduction=D?Math.max(0,D.max-Math.max(0,gross-D.from)*D.taper):0;
  return Math.max(0,irpfScale(base)-irpfScale(LAW.irpf.personalAllowance)-deduction);
}
/**
 * IRPF that a gross adds to what you already earn that year. If the offer spans two years, the gross is split by days
 * between them (cfg.irpfShares: [{f: share of the gross, others: your other offers that year, ded: that year's deduction}]).
 */
const irpfExtra = (gross,cfg)=>(cfg.irpfShares||[{f:1,others:0,ded:cfg.dedSMI}]).reduce((s,t)=>{
  const base=num(cfg.others)+t.others; return s+irpfTax(base+t.f*gross,cfg.ssPct,t.ded)-irpfTax(base,cfg.ssPct,t.ded)},0);

/** Smallest x in [lo,hi] with f(x) ≥ targetVal, by bisection (f increasing). */
function bisect(f,targetVal,lo,hi,steps){
  for(let i=0;i<steps;i++){ const m=(lo+hi)/2; if(f(m)<targetVal) lo=m; else hi=m }
  return hi;
}

/** Unemployment benefit generated by a gross contributed over `contrib` days. */
function unemploymentBenefit(gross,contrib){
  if(gross<=0||contrib<=0) return {days:0,euros:0};
  const P=LAW.unemployment, days=contrib/P.contribPerDay, base=gross/contrib, mn=P.minMonth/30, mx=P.maxMonth/30;
  const d1=Math.min(days,P.days70), d2=days-d1, perDay=pct=>clamp(base*pct,mn,mx);
  return {days, euros:(d1*perDay(P.pct1)+d2*perDay(P.pct2))*(1-P.contribRate)};
}

/** Payroll months of a contract of `days` calendar days from `a`: whole calendar months and the rest at 1/30. */
function payrollMonths(a,days){
  const end=new Date(a); end.setDate(end.getDate()+Math.round(days)); // the day after the last one
  let n=0; const m=()=>{const x=new Date(a); x.setMonth(x.getMonth()+n+1); return x};
  while(m()<=end) n++;
  const from=new Date(a); from.setMonth(from.getMonth()+n);
  return n+Math.min(30,Math.round((end-from)/864e5))/30;
}
/** Time: duration, days worked and off, hours. */
function schedule(o,cfg=config){
  const noDuration=o.durationUnit==='unknown';
  // In days and with a start date, months are counted as on the payslip: whole calendar months and the days
  // left over at 1/30 of a month (21 jun – 30 sep: 3 months and 10 days = 3.33). Without a date, with an average month of 30.42 days.
  const days=o.durationUnit==='days'?Math.max(0,num(o.duration)):0;
  const months=noDuration?1:o.durationUnit==='days'?(o.start&&days>0?payrollMonths(parseDate(o.start),days):days/DM):Math.max(0,num(o.duration));
  const h=Math.max(0,num(o.hoursPerDay)), off=Math.max(0,num(o.daysOff));
  // Vacation: 2.5 days per month, rounded to whole days, as on payslips (8.33 → 8)
  const natDays=o.durationUnit==='days'&&!noDuration?days:months*DM, vacationExact=num(cfg.vacationDaysPerYear)*months/12, vacationDays=Math.round(vacationExact);
  const vacationTaken=o.vacation==='taken'?vacationDays:0;
  // Share of days you work. «En total»: the days off over the whole contract, not counting vacation
  const lu=noDuration&&o.daysOffUnit==='total'?'month':o.daysOffUnit, rest=Math.max(0,natDays-vacationTaken);
  const workFrac=lu==='week'?clamp((7-off)/7,0,1):lu==='total'?(rest>0?clamp((rest-off)/rest,0,1):0):clamp((DM-off)/DM,0,1);
  const holidayDays=o.holidays==='yes'?LAW.holidaysPerYear*months/12:0; // the public holidays you take off, on top of the days off
  // Whole days when there is a duration: days off per month are an average, but nobody works half a day (91.9 → 92).
  // Without a duration an average month is used and the figure stays an average.
  const daysExact=Math.max(0,(natDays-vacationTaken-holidayDays)*workFrac), daysWorked=noDuration?daysExact:Math.round(daysExact);
  return {noDuration,months,h,workFrac,natDays,vacationDays,vacationTaken,daysWorked,
    freeDays:Math.max(0,natDays-daysWorked), daysOffTotal:Math.max(0,(natDays-vacationTaken)*(1-workFrac)),
    hoursPerWeek:workFrac*7*h, hours:daysWorked*h};
}

/** Payroll: gross (if you are told the net, it finds the gross that gives it), Social Security and IRPF. */
function payroll(o,cfg,t){
  const a=num(o.payAmount);
  // «Total»: what is paid on payroll over the whole contract (without a duration, taken as one month)
  // «Per day» on payroll: the daily wage is also paid on the vacation days and public holidays you take off (paid days,
  // ET art. 37.2 and 38); in cash, only the days you work.
  const monthly=o.payUnit==='day'?a*DM*t.workFrac:o.payUnit==='month'?a:o.payUnit==='total'?(t.noDuration?a:t.months>0?a/t.months:0):a/12;
  // Per day: the daily wage for each paid day (the contract's days, minus the days-off share). With a date, months
  // are counted as on the payslip and do not have 30.4 days: multiplying by months would inflate or shrink the pay.
  let base=o.payUnit==='day'?a*t.workFrac*t.natDays:monthly*t.months;
  let extraPays=(o.extraPays==='separate'&&!['year','total'].includes(o.payUnit))?monthly*2*t.months/12:0;
  // A vacation day: the month's salary divided by 30, with prorated extra payments if they are included, as payslips do
  // (with the minimum wage: the annual one divided by 420, as in the legal minimum)
  // It is the page's estimate, not your data: never below one day at the minimum wage (otherwise it would invent a debt)
  const partFactor=Math.min(1,t.workFrac*7*t.h/LAW.weeklyHours);
  const vacationDay=Math.max(monthly/30, cfg.smiAnnual/LAW.smiDaysPerYear*partFactor);
  let vacationPay=o.vacation==='paidAtEnd'?(o.vacationGross!=null?o.vacationGross:t.vacationDays*vacationDay):0; // vacationGross: with «the minimum on payroll», the legal-minimum vacation
  // «Included in the daily wage»: the agreed pay already contains the vacation. It is split into salary and vacation (a vacation day,
  // as above, from the remaining salary); the total does not change. With a contract it shows on the payslip as a separate item.
  if(o.vacation==='included'&&base>0&&t.months>0){
    const q=1/30, s=base/(t.months+t.vacationDays*q); // monthly salary left after taking the vacation out
    vacationPay=t.vacationDays*s*q; base=s*t.months;
  }
  // IRPF withholding on the payslip: yours if you set it; otherwise the one that matches what you earn in the year,
  // and at least 2 % for temporary contracts (the minimum for casual farm workers). The net is what reaches your account:
  // gross − Social Security − withholding. What is settled in the tax return (irpfYear) is separate, only as a note.
  const irpfYearOf=B=>o.irpfMode==='manual'?B*num(o.irpfManual)/100:irpfExtra(B,cfg);
  const withholdingOf=B=>o.irpfMode==='manual'?irpfYearOf(B):Math.max(irpfYearOf(B),o.contract==='temporary'?B*LAW.irpf.withholding/100:0);
  const netOf=B=>B-B*cfg.ssPct/100-withholdingOf(B);
  let grossTotal=base+extraPays+vacationPay, ratio=1;
  if(o.payType==='net'&&grossTotal>0){
    const net=grossTotal;
    grossTotal=bisect(netOf,net,net,net*3,60);
    ratio=grossTotal/net; base*=ratio; extraPays*=ratio; vacationPay*=ratio;
  }
  const ss=grossTotal*cfg.ssPct/100, irpf=withholdingOf(grossTotal), netTotal=grossTotal-ss-irpf;
  return {a,ratio,base,extraPays,vacationPay,grossTotal,ss,irpf,irpfYear:irpfYearOf(grossTotal),netTotal,fac:grossTotal>0?netTotal/grossTotal:0,netOf};
}

/** Vacation you do not take and are paid for: separately at the end or inside the daily wage. */
const vacationPaid=o=>o.vacation==='paidAtEnd'||o.vacation==='included';
/** The page works out the cash part: the agreed total minus what reaches you on payroll (only with a contract). */
const fromTotal=o=>o.cashMode==='total'&&o.contract!=='none';
/**
 * The offer as it is calculated.
 * · «Usar el salario mínimo»: the payroll is the applicable minimum wage (the casual-worker one for temporary contracts
 *   of 120 days or less), with the vacation you do not take paid at the minimum.
 * · «Total pactado»: the cash part is the agreed total (all together: payroll, vacation and cash) minus what
 *   reaches you on payroll, salary and vacation, net. If the total does not even reach that, nothing is left in cash.
 */
function effective(o,cfg=config){
  if(o.contract==='none'||(!o.payrollMin&&!fromTotal(o))) return o;
  const t=schedule(o,cfg), m=legalMinimum(o,cfg,t);
  let x=o;
  // «Included in the agreed pay»: legally it shows on the payslip as a separate item; with «Total pactado», the cash part drops by the same
  const incl=o.vacation==='included';
  if(fromTotal(o)&&incl) x={...x,vacation:'paidAtEnd'};
  if(o.payrollMin) x={...x,vacation:x.vacation==='included'?'paidAtEnd':x.vacation,payType:'gross',payAmount:m.minSalary,payUnit:'total',extraPays:'included',vacationGross:m.minVacation};
  if(!fromTotal(o)) return x;
  const n=payroll(x,cfg,t), netPayroll=n.netTotal; // everything on payroll, vacation included
  const T=num(o.totalAmount), u=o.totalUnit;
  const totalAll=u==='day'?T*t.daysWorked:u==='month'?T*t.months:T;
  const vacationNet=n.vacationPay*n.fac, payrollNet=netPayroll-vacationNet;
  // Paid separately: extra money, not taken from the total; included: taken from the total (the cash part drops)
  const takenFromTotal=incl?netPayroll:payrollNet, B=Math.max(0,totalAll-takenFromTotal);
  const div=u==='day'?t.daysWorked:u==='month'?t.months:1, perUnit=v=>div>0?v/div:0;
  return {...x,cashAmount:B,cashUnit:'total',
    split:{u,T,incl,min:!!o.payrollMin,casual:m.casual,shortfall:T>0&&totalAll<takenFromTotal-0.5,gross:perUnit(n.grossTotal),net:perUnit(netPayroll),payrollNet:perUnit(payrollNet),vacationNet:perUnit(vacationNet),b:perUnit(B),cashTotal:B}};
}
/** An amount in the split's unit: 52,93 €/día · 1.140 €/mes · 4.000 € en total. */
const fSplit=(v,u)=>u==='total'?`${fE(v)} en total`:u==='day'?`${fE(v,Math.abs(v-Math.round(v))<0.005?0:2)}/día`:`${fE(v)}/mes`;

/** Car: trips home, km and their cost; km paid by the employer. */
function travel(o,t,cfg=config){
  // Only work trips: every day, or up at the start and down at the end if you live there
  const trips = o.car==='noCar' ? 0 : o.commute==='daily' ? t.daysWorked : 0;
  // If you live there: up at the start and down at the end, plus the trips home on days off
  const tripsTotal=trips+(o.car!=='noCar'&&o.commute!=='daily'?(t.noDuration?0:1)+num(o.tripsHome)*t.months:0);
  const kmTrips=num(o.kmHome)*2*tripsTotal, kmWork=o.car==='own'?num(o.kmWorkPerDay)*t.daysWorked:0;
  const costPerKm=num(cfg.fuelUse)/100*num(cfg.fuelPrice)+num(cfg.wear);
  return {trips, km:kmTrips+kmWork, car:(kmTrips+kmWork)*costPerKm, kmPaid:kmWork*num(o.kmRate)};
}

/** Legal minimum, counted by months (what the paperwork shows). */
function legalMinimum(o,cfg,t){
  const {noDuration,months,h,workFrac,natDays,vacationDays,daysWorked}=t;
  const smiDay=cfg.smiAnnual/LAW.smiDaysPerYear, partFactor=Math.min(1,workFrac*7*h/LAW.weeklyHours);
  const casual=!noDuration&&o.contract==='temporary'&&natDays<=LAW.casualMaxDays;
  const minSalary=casual?cfg.smiCasual*daysWorked*Math.min(1,h/LAW.workdayHours):cfg.smiAnnual*months/12*partFactor;
  const minVacation=(casual||o.vacation!=='taken')?vacationDays*smiDay*partFactor:0;
  const overnightF=o.overnight==='yes'?cfg.overnightPct/100:0;
  const smiHour=cfg.smiAnnual/cfg.annualHours, overnightPay=overnightF*minSalary; // monthly (or casual) minimum wage, overnight bonus and vacation not taken
  return {casual,overnightF,smiHour,minSalary:minSalary,minVacation:minVacation,overnightPay,minBy:{month:minSalary+minVacation+overnightPay}};
}

/**
 * Extra time, with the two rules of the law: at least a day and a half of rest per week (plus public holidays), and
 * 40 h of work a week, spread over those 5.5 days (about 7.3 h a day).
 * · Due workdays: the contract's days without the weekly rest, public holidays or the vacation you take.
 *   Vacation you do not take is due: you work those days, and the vacation money is separate.
 * · Extra days: the ones you work above that (rest days or public holidays you do not take).
 * · Overtime: hours above 40 a week, not counting those of the extra days.
 * The normal workday is paid at the minimum; what you are paid above it covers the extra days first and then the hours.
 */
const NORMAL_WORKDAY=LAW.weeklyHours/(7-LAW.weeklyRest); // 7.27 h
function extraTime(t,cfg,m,grossTotal,cashGrossEq){
  const {months,h,daysWorked,hours}=t;
  const smiHourRef=m.smiHour, holidaysN=LAW.holidaysPerYear*months/12, base=Math.max(0,t.natDays-t.vacationTaken);
  const due=Math.max(0,base*(7-LAW.weeklyRest)/7-holidaysN);
  // The normal workday: the 40 h spread over the days you work per week, at least 5.5 (7.3 h) and
  // at most 9 h (ET art. 34.3). If you get more than a day and a half off, your normal days are longer.
  const daysWeek=base>0?Math.round(daysWorked/(base/7)*10)/10:0; // rounded: «5 días», not «4,99»; so the bar and the total match
  const workday=Math.min(h,Math.min(LAW.workdayMaxHours,LAW.weeklyHours/(daysWeek>0?Math.min(7-LAW.weeklyRest,daysWeek):7-LAW.weeklyRest)))||NORMAL_WORKDAY;
  // Extra days: the days you work above the due workdays; each is worth one normal workday.
  // Overtime: what goes over the normal workday, on every day you work (extra days included).
  // Each extra hour is counted once: either in an extra day or as overtime.
  const daysExtra=Math.max(0,daysWorked-due), daysLab=Math.min(daysWorked,due), hOver=daysWorked*Math.max(0,h-workday);
  const hoursExtra=daysExtra*workday+hOver, hoursNorm=Math.max(0,hours-hoursExtra);
  // Days you work per week, on average (rounded: «5 días», not «4,99»)
  const workDaysWeek=daysWeek||7-LAW.weeklyRest;
  // What the normal workday pays: the same legal minimum as «Te deben» (salary, bonus and vacation). Casual workers
  // are paid the minimum per day worked, so only the due workdays count against that minimum, not the extra ones.
  const normFactor=m.casual&&daysWorked>0?Math.min(1,due/daysWorked):1;
  const minNormal=(m.minSalary+m.overnightPay)*normFactor+m.minVacation;
  return {tmHoursNorm:hoursNorm,tmDue:due,tmHolidays:holidaysN,tmDays:daysExtra,tmHoursOver:hOver,tmHours:hoursExtra,tmMinPay:minNormal,
    tmDayRef:smiHourRef*workday*(1+m.overnightF),tmWorkday:workday,tmDaysLab:daysLab,tmWorkDaysWeek:workDaysWeek,tmHoursDay:h};
}

/** Which share of an offer falls in each year, by days: {2025: 0.4, 2026: 0.6}. Without a date, all in its year. */
function yearShares(o){
  if(!o.start||!endOf(o)) return {[actualYear(o)]:1};
  const [a,f]=span(o), tot=(f-a)/864e5+1, P={};
  for(let y=a.getFullYear();y<=f.getFullYear();y++){
    const start=Math.max(+a,+new Date(y,0,1)), end=Math.min(+f,+new Date(y,11,31));
    if(end>=start) P[y]=((end-start)/864e5+1)/tot;
  }
  return P;
}
const deductionOf=y=>SMI[clamp(+y,+YEARS[0],+YEARS.at(-1))].ded;
/**
 * For IRPF: for each year this offer touches, the share of its gross that falls in it and what you earn on payroll that year
 * in your other worked offers (also split by days). The others are calculated without this sum, to avoid going round in circles.
 */
function othersInYear(o){
  const P=yearShares(o), otherOffers=o.start?workedOffers().filter(p=>p.id!==o.id&&!missing(p).length).map(p=>({p,b:calc(p,config,{noOthers:true}).grossTotal,P:yearShares(p)})):[];
  const shares=Object.entries(P).map(([y,f])=>({f,ded:deductionOf(y),others:otherOffers.reduce((s,x)=>s+x.b*(x.P[y]||0),0)}));
  const used=otherOffers.filter(x=>x.b>0.5&&Object.keys(P).some(y=>x.P[y]));
  return {shares, gross:shares.reduce((s,t)=>s+t.others,0), n:used.length, years:Object.keys(P)};
}
/**
 * Every figure of an offer. Money is in € over the whole contract
 * unless the name says otherwise (perDay, perMonth…).
 */
function calc(o,cfg=config,{noOthers=false}={}){
  const year=yearOf(o), S=SMI[year], othersIncome=noOthers?{gross:0,n:0,shares:null,years:[year]}:othersInYear(o);
  // the minimum wage of the offer's year and, for IRPF, each year it touches with the rest of what you earn in it
  cfg={...cfg,smiAnnual:S.annual,smiCasual:S.casual,dedSMI:S.ded,irpfShares:noOthers?null:othersIncome.shares};
  // Without a contract there is no payroll and no paid vacation: everything is cash. The legal minimum is that of a temporary contract.
  const split=fromTotal(o)?effective(o,cfg).split:null; o=effective(o,cfg);
  const noContract=o.contract==='none';
  if(noContract) o={...o,payAmount:0,vacation:'included',extraPays:'included',contract:'temporary'};
  const t=schedule(o,cfg), n=payroll(o,cfg,t), d=travel(o,t,cfg), m=legalMinimum(o,cfg,t);
  const {noDuration,months,h,workFrac,natDays,vacationDays,vacationTaken,daysWorked,daysOffTotal,hours,hoursPerWeek}=t;
  const {grossTotal,netTotal,fac}=n;

  // Cash, housing and food, expenses
  const cashQty=num(o.cashAmount), B=o.cashUnit==='month'?cashQty*months:o.cashUnit==='day'?cashQty*daysWorked:cashQty;
  const housingValue=cfg.inKind&&o.housing==='yes'?rentPerMonth(o,cfg)*months:0;
  const foodValue=cfg.inKind?foodPerDay(o,cfg)*daysWorked:0;
  const otherExpenses=num(o.expenses)*months, expenses=d.car+otherExpenses;

  // Unemployment benefit you generate, and the gross needed to pay you the cash part on payroll with the same net (what the employer saves)
  const contrib=grossTotal>0?natDays+(vacationPaid(o)?vacationDays:0):0;
  const unemployment=unemploymentBenefit(grossTotal,contrib);
  const netPayroll=n.netOf(grossTotal);
  const cashGrossEq=B>0?bisect(x=>n.netOf(grossTotal+x)-netPayroll,B,B,B*3,50):0; // gross needed for the cash part to arrive net


  // Cost to the employer
  const salaryPerDay=natDays>0?(n.base+n.extraPays)/natDays:0;
  const severancePay=!noDuration&&o.contract==='temporary'?salaryPerDay*LAW.severanceDaysPerYear*natDays/365:0;

  // What you earn
  // The unemployment benefit you generate counts as your money (it can be switched off in «Supuestos del cálculo»): it is what cash does not give
  const comp={base:n.base*fac,extraPays:n.extraPays*fac,vacationPay:n.vacationPay*fac,b:B,housing:housingValue,food:foodValue,km:d.kmPaid,severance:severancePay,unemployment:cfg.unemployment!==false?unemployment.euros:0};
  const total=Object.values(comp).reduce((s,x)=>s+x,0)-expenses;
  const perMonth=x=>months>0?x/months:0;

  // Weekly rest and hours above 40
  const restLegal=(natDays-vacationTaken)*LAW.weeklyRest/7;
  // What you are owed, counted by months: what is missing in each item separately (a surplus in one does not cover another)
  const salaryGross=n.base+n.extraPays;
  let debtSalary=Math.max(0,m.minSalary+m.overnightPay-salaryGross), minNetNoContract=0;
  let debtVacation=o.vacation==='taken'?0:Math.max(0,m.minVacation-n.vacationPay), debtTotal=debtSalary+debtVacation;
  let minShare=m.minBy.month>0?(debtTotal>1?1-debtTotal/m.minBy.month:grossTotal/m.minBy.month):0;
  if(noContract){ // what you are paid in cash against the minimum wage (with overnight bonus), converted to net
    const f=fac>0?fac:1-cfg.ssPct/100, minSalary=m.minSalary+m.overnightPay; minNetNoContract=minSalary*f; // the same net↔gross factor as everything else
    debtSalary=Math.max(0,minSalary-B/f); debtVacation=m.minVacation; debtTotal=debtSalary+debtVacation; // without a contract there is no paid vacation
    minShare=minSalary+m.minVacation>0?B/f/(minSalary+m.minVacation):0;
  }

  const r={
    // time
    split,othersIncome,year,smiA:S.annual,smiEv:S.casual,smiRd:S.rd,smiUrl:S.url,noDuration,months,natDays,vacationDays,vacationTaken:t.vacationTaken,daysWorked,freeDays:t.freeDays,daysOffTotal,hours,hoursPerWeek,
    daysOffMonth:perMonth(daysOffTotal),workedPerMonth:perMonth(daysWorked),
    // payroll
    payGross:n.a*n.ratio,payNet:n.a*n.ratio*fac,grossTotal,ss:n.ss,irpf:n.irpf,irpfYear:n.irpfYear,netTotal,fac,irpfPct:grossTotal>0?n.irpf/grossTotal:0,
    // cash, in kind, expenses
    B,cashShare:(netTotal+B)>0?B/(netTotal+B):0,inKind:housingValue+foodValue,expenses,car:d.car,otherExpenses,km:d.km,trips:d.trips,kmPaid:d.kmPaid,
    // what you earn
    comp,total,perDay:daysWorked>0?total/daysWorked:0,perHour:hours>0?total/hours:0,perMonth:perMonth(total),
    extraPaysNet:comp.extraPays,vacationPayNet:comp.vacationPay,
    // unemployment benefit and cash
    contrib,unemploymentDays:unemployment.days,unemployment:unemployment.euros,cashGrossEq,
    // cost to the employer
    ssEmployer:grossTotal*cfg.ssEmp/100,severancePay,
    cost:grossTotal*(1+cfg.ssEmp/100)+B+housingValue+foodValue+d.kmPaid+severancePay,cashSavings:cashGrossEq*(1+cfg.ssEmp/100)-B,
    // legal minimum, rest and working hours
    casual:m.casual,minSalary:m.minSalary,overnightPay:m.overnightPay,minVacation:m.minVacation,salaryGross,vacationPayGross:n.vacationPay,minBy:m.minBy,
    smiHour:m.smiHour,
    debtSalary,debtVacation,debtTotal,minShare,minNetNoContract,grossPerHour:hours>0?grossTotal/hours:0,
    noContract,restLegal,restShort:Math.max(0,restLegal-daysOffTotal),
    ...extraTime(t,cfg,m,grossTotal,cashGrossEq),
  };
  return Object.assign(r,derived(r,cfg));
}


/**
 * What comes out of calc()'s figures and is used by more than one part of the page: it is worked out once, here, and stored
 * in the result (r.savings, r.owed…). The functions below only read it. All in € over the whole contract and gross,
 * unless stated otherwise.
 */
function derived(r,cfg){
  const emp=1+cfg.ssEmp/100, sem=(r.noDuration?DM:r.natDays)/7, cashGrossEq=r.B>0?r.cashGrossEq:0;
  // What you are owed, by parts: salary up to the minimum wage, overnight bonus and vacation
  const dSal=Math.max(0,r.minSalary-r.salaryGross)*(r.noContract?0:1)+(r.noContract?Math.max(0,r.debtSalary-r.overnightPay):0);
  const debtParts={salary:dSal, overnight:Math.max(0,r.debtSalary-dSal), vac:r.debtVacation};
  // What you are really owed: what is missing on payroll minus what the cash part covers (without a contract, already counted).
  // A payroll below the minimum is flagged separately, even if cash covers it: cash does not pay contributions.
  const owed=r.noContract?r.debtTotal:Math.max(0,r.debtTotal-cashGrossEq);
  // Extra days and overtime: what you are paid above the legal minimum (payroll and cash) covers the extra days
  // first (each one, a workday at the minimum wage) and whatever is left, the overtime (each one, an hour at the minimum wage)
  const paysAbove=(r.grossTotal>0||r.noContract)?Math.max(0,r.grossTotal-r.tmMinPay+cashGrossEq):0;
  const daysValue=r.tmDays>=0.5?r.tmDays*r.tmDayRef:0, overtimeValue=r.tmHoursOver*r.smiHour;
  const daysUnpaid=Math.max(0,daysValue-paysAbove), overtimeUnpaid=Math.max(0,overtimeValue-Math.max(0,paysAbove-daysValue));
  // What the employer saves at your expense, with their Social Security (their margin to negotiate):
  // · b: contributions on the cash part (or on everything, without a contract): what putting it on payroll would cost without you earning less
  // · min: what is missing from the minimum and not covered by cash · days and extra: what is missing for the extra days and the overtime
  const b=r.cashSavings>1?r.cashSavings:0, shortfall=owed, min=shortfall>1?shortfall*emp:0;
  const daysSavings=daysValue>0&&daysUnpaid>1?daysUnpaid*emp:0, overtimeSavings=overtimeValue>0&&overtimeUnpaid>1?overtimeUnpaid*emp:0;
  const savings={b,min,shortfall,days:daysSavings,daysUnpaid,daysValue,extra:overtimeSavings,overtimeUnpaid,overtimeValue,
    daysUnpaidEq:r.tmDayRef>0?daysUnpaid/r.tmDayRef:0, overtimeUnpaidWeek:overtimeValue>0?overtimePerWeek(r)*overtimeUnpaid/overtimeValue:0, overtimeWeek:overtimePerWeek(r), over40Week:hoursWeek(r).over,
    total:b+min+daysSavings+overtimeSavings};
  // The stamp on the headline figure: the most serious issue. Red if serious; amber if only the overnight bonus is missing
  const stamp=r.noContract?['Sin contrato','']:r.cashShare>=0.995?['Todo en negro','']:debtParts.salary>1?['Bajo el mínimo','']:debtParts.overnight>1?['Sin plus',' warn']:['',''];
  return {owed,debtParts,savings,stamp,received:r.comp.base+r.comp.extraPays+r.comp.vacationPay+r.comp.b+r.comp.km,
    unemploymentLost:r.noContract?unemploymentBenefit(cashGrossEq,r.noDuration?DM:r.natDays):null};
}
