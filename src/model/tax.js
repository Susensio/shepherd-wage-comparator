/** IRPF and the unemployment benefit: Spanish tax and benefit rules, as pure functions. */

import { clamp, num } from '../format.js';
import { LAW } from '../law.js';

/** Tax on a base along the IRPF scale. */
function scaleTax(base) {
  let tax = 0;
  let previous = 0;
  for (const [cap, rate] of LAW.irpf.scale) {
    if (base <= previous) break;
    tax += (Math.min(base, cap) - previous) * rate;
    previous = cap;
  }
  return tax;
}

/** Earned-income reduction (LIRPF art. 20). */
function workReduction(netIncome) {
  const w = LAW.irpf.workReduction;
  if (netIncome <= w.fullTo) return w.full;
  if (netIncome <= w.midTo) return Math.max(0, w.full - w.midSlope * (netIncome - w.fullTo));
  if (netIncome <= w.lowTo) return Math.max(0, w.lowFrom - w.lowSlope * (netIncome - w.midTo));
  return 0;
}

/**
 * IRPF for a year on an annual gross: general scale, no children, with the deduction for wages near the minimum wage.
 * @param {number} gross
 * @param {number} ssPct worker's Social Security, %
 * @param {{max: number, from: number, taper: number} | null} deduction that year's minimum-wage deduction
 */
export function irpfTax(gross, ssPct, deduction) {
  if (gross <= 0) return 0;
  const netIncome = Math.max(0, gross - (gross * ssPct) / 100 - LAW.irpf.expenses);
  const base = Math.max(0, netIncome - workReduction(netIncome));
  const credit = deduction ? Math.max(0, deduction.max - Math.max(0, gross - deduction.from) * deduction.taper) : 0;
  return Math.max(0, scaleTax(base) - scaleTax(LAW.irpf.personalAllowance) - credit);
}

/**
 * IRPF that a gross adds to what you already earn in the year. If the offer spans two years, the gross is split
 * between them by days: `shares` holds, per year, the share of the gross, what your other offers earn then and that year's deduction.
 * @param {number} gross
 * @param {{others: number}} cfg
 * @param {{share: number, others: number, deduction: object | null}[]} shares
 */
export const irpfAdded = (gross, cfg, shares) =>
  shares.reduce((sum, { share, others, deduction }) => {
    const base = num(cfg.others) + others;
    return sum + irpfTax(base + share * gross, LAW.ssWorkerPct, deduction) - irpfTax(base, LAW.ssWorkerPct, deduction);
  }, 0);

/**
 * Unemployment benefit generated by a gross contributed over some days.
 * @returns {{days: number, euros: number}}
 */
export function unemploymentBenefit(gross, contribDays) {
  if (gross <= 0 || contribDays <= 0) return { days: 0, euros: 0 };
  const u = LAW.unemployment;
  const days = contribDays / u.contribPerDay;
  const base = gross / contribDays;
  const perDay = (pct) => clamp(base * pct, u.minMonth / 30, u.maxMonth / 30);
  const first = Math.min(days, u.days70);
  return { days, euros: (first * perDay(u.pct1) + (days - first) * perDay(u.pct2)) * (1 - u.contribRate) };
}

/** Smallest x in [lo, hi] with f(x) ≥ target, by bisection (f increasing). */
export function bisect(f, target, lo, hi, steps) {
  for (let i = 0; i < steps; i++) {
    const mid = (lo + hi) / 2;
    if (f(mid) < target) lo = mid;
    else hi = mid;
  }
  return hi;
}
